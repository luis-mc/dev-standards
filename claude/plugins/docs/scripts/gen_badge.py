"""gen_badge: the one place that says which luismc-docs made a page, and whether it is the newest.

Used by every renderer (record pages, docs site, design-system gallery, generated Markdown and text).
Standard library only. It never reads the network.

"Latest" is judged at build time. The plugin's own version comes from .claude-plugin/plugin.json.
The newest published version comes from a local marketplace clone: Claude Code keeps clones under
<home>/.claude/plugins/marketplaces/<name>/. The entry for this plugin is found by name in the
marketplace's .claude-plugin/marketplace.json; its source path leads to a plugin.json to read.
With no clone, the state is `unknown`.

Set LUISMC_MARKETPLACES_DIR to look somewhere else (tests do).
"""
from __future__ import annotations

import html
import json
import os
import re
from pathlib import Path

PLUGIN_DIR = Path(__file__).resolve().parent.parent
ENV_DIR = "LUISMC_MARKETPLACES_DIR"
# Matches the plain header line of generated text, with or without the HTML comment wrapper.
LINE_RE = re.compile(r"^(?:<!-- )?Generated by luismc-docs \d[^\n]*\n?", re.M)

BADGE_CSS = (
    ".gen-badge{display:inline-flex;align-items:center;gap:.4em;font-family:var(--font-mono,ui-monospace,Consolas,monospace);"
    "font-size:.72rem;white-space:nowrap}"
    ".gen-flag{display:inline-block;padding:0 .5em;border:1px solid currentColor;border-radius:3px;line-height:1.5}"
    ".gen-latest{color:#17784A}.gen-update{color:#B26A00}.gen-unknown{color:#6b7380}"
    "@media (prefers-color-scheme:dark){:root:not([data-theme=light]) .gen-latest{color:#4CC38A}"
    ":root:not([data-theme=light]) .gen-update{color:#F0B54A}:root:not([data-theme=light]) .gen-unknown{color:#9AA5B4}}"
    ":root[data-theme=dark] .gen-latest{color:#4CC38A}:root[data-theme=dark] .gen-update{color:#F0B54A}"
    ":root[data-theme=dark] .gen-unknown{color:#9AA5B4}"
)


def _read_json(path: Path):
    try:
        data = json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError):
        return None
    return data if isinstance(data, dict) else None


def own_info(plugin_dir: Path = PLUGIN_DIR) -> tuple[str, str]:
    data = _read_json(Path(plugin_dir) / ".claude-plugin" / "plugin.json") or {}
    return str(data.get("name") or "luismc-docs"), str(data.get("version") or "0.0.0")


def version_key(v: str) -> tuple:
    return tuple(int(p) for p in re.findall(r"\d+", v.split("-")[0].split("+")[0]))


def marketplaces_dir() -> Path:
    env = os.environ.get(ENV_DIR)
    return Path(env) if env else Path.home() / ".claude" / "plugins" / "marketplaces"


def newest_published(name: str, base: Path | None = None) -> str | None:
    """The highest version of plugin `name` in any local marketplace clone, else None."""
    base = Path(base) if base else marketplaces_dir()
    best = None
    try:
        clones = sorted(p for p in base.iterdir() if p.is_dir())
    except OSError:
        return None
    for clone in clones:
        market = _read_json(clone / ".claude-plugin" / "marketplace.json")
        for entry in (market or {}).get("plugins") or []:
            if not isinstance(entry, dict) or entry.get("name") != name or not isinstance(entry.get("source"), str):
                continue
            src = (clone / entry["source"]).resolve()
            if clone.resolve() not in src.parents and src != clone.resolve():
                continue  # a source path must stay inside the clone
            ver = (_read_json(src / ".claude-plugin" / "plugin.json") or {}).get("version")
            if isinstance(ver, str) and version_key(ver) and (best is None or version_key(ver) > version_key(best)):
                best = ver
    return best


def status(plugin_dir: Path = PLUGIN_DIR, base: Path | None = None) -> dict:
    """{'name', 'version', 'state': 'latest'|'update'|'unknown', 'newest': str|None}."""
    name, version = own_info(plugin_dir)
    newest = newest_published(name, base)
    if newest is None:
        state = "unknown"
    elif version_key(newest) > version_key(version):
        state = "update"
    else:
        state = "latest"
    return {"name": name, "version": version, "state": state, "newest": newest}


def flag_text(s: dict) -> str:
    return {"latest": "latest", "update": "update: %s" % s["newest"], "unknown": "latest: unknown"}[s["state"]]


def badge_html(s: dict | None = None) -> str:
    s = s or status()
    return ('<span class="gen-badge" data-gen-state="%s">%s %s <span class="gen-flag gen-%s">%s</span></span>'
            % (s["state"], html.escape(s["name"]), html.escape(s["version"]), s["state"], html.escape(flag_text(s))))


def line_text(s: dict | None = None) -> str:
    """`Generated by luismc-docs X.Y.Z (latest|update: X.Y.Z|latest: unknown)`."""
    s = s or status()
    return "Generated by %s %s (%s)" % (s["name"], s["version"], flag_text(s))


def md_line(s: dict | None = None) -> str:
    return "<!-- %s -->" % line_text(s)


def strip_badge_line(text: str) -> str:
    """For freshness checks: the text without its badge line, so a build with and without a marketplace clone agree."""
    return LINE_RE.sub("", text)


def generator_value(s: dict | None = None) -> str:
    """The `generator:` front matter value for a new feature spec: `luismc-docs X.Y.Z`."""
    s = s or {}
    name, version = (s["name"], s["version"]) if s else own_info()
    return "%s %s" % (name, version)


_FLAG_RE = re.compile(r'<span class="gen-flag [^"]*">[^<]*</span>')
_STATE_RE = re.compile(r' data-gen-state="\w+"')


def strip_flag_html(page: str) -> str:
    """For freshness checks of a rendered page: the page without the latest-state flag. The plugin name and
    version stay in, so an upgrade still makes a page stale; a different marketplace clone does not."""
    return _STATE_RE.sub("", _FLAG_RE.sub("", page))
