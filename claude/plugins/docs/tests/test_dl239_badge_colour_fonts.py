def fake_market(base: Path, version, name="luismc-docs", market="mk"):
    clone = base / market
    (clone / ".claude-plugin").mkdir(parents=True)
    (clone / "pkg" / ".claude-plugin").mkdir(parents=True)
    (clone / ".claude-plugin" / "marketplace.json").write_text(
        json.dumps({"name": market, "plugins": [{"name": "other", "source": "./nope"}, {"name": name, "source": "./pkg"}]}), encoding="utf-8")
    (clone / "pkg" / ".claude-plugin" / "plugin.json").write_text(json.dumps({"name": name, "version": version}), encoding="utf-8")


class BadgeHelper(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.base = Path(self.tmp.name)
        self.own = B.own_info()[1]

    def test_latest_when_same_version(self):
        fake_market(self.base, self.own)
        s = B.status(base=self.base)
        self.assertEqual(s["state"], "latest")
        self.assertIn("latest", B.badge_html(s))
        self.assertEqual(B.line_text(s), "Generated by luismc-docs %s (latest)" % self.own)

    def test_update_names_newer_version(self):
        fake_market(self.base, "99.0.1")
        s = B.status(base=self.base)
        self.assertEqual(s["state"], "update")
        self.assertIn("update: 99.0.1", B.badge_html(s))
        self.assertIn("gen-update", B.badge_html(s))
        self.assertTrue(B.line_text(s).endswith("(update: 99.0.1)"))

    def test_numeric_compare_not_text(self):
        fake_market(self.base, "0.0.1")
        self.assertEqual(B.status(base=self.base)["state"], "latest")

    def test_unknown_without_clone(self):
        s = B.status(base=self.base / "missing")
        self.assertEqual(s["state"], "unknown")
        self.assertIn("latest: unknown", B.badge_html(s))
        s2 = B.status(base=self.base)  # empty dir
        self.assertEqual(s2["state"], "unknown")

    def test_badge_names_plugin_and_version(self):
        self.assertIn("luismc-docs %s" % self.own, B.badge_html(B.status(base=self.base)))

    def test_strip_badge_line_makes_builds_agree(self):
        a = "<!-- x -->\n%s\n# T\n" % B.md_line({"name": "luismc-docs", "version": "1.0.0", "state": "latest", "newest": "1.0.0"})
        b = "<!-- x -->\n%s\n# T\n" % B.md_line({"name": "luismc-docs", "version": "1.0.0", "state": "unknown", "newest": None})
        self.assertNotEqual(a, b)
        self.assertEqual(B.strip_badge_line(a), B.strip_badge_line(b))
        self.assertIn("> Generated by luismc-docs. Read", B.strip_badge_line("> Generated by luismc-docs. Read docs\n"))


class Generated(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name) / "proj"
        (self.root / "docs" / "features" / "alpha").mkdir(parents=True)
        (self.root / "docs" / "README.md").write_text("# Docs\n", encoding="utf-8")
        (self.root / "docs" / "features" / "alpha" / "spec.md").write_text(
            "---\nid: alpha\ntitle: Alpha\napps: []\ntopics: []\nstatus: live\nversion: 1.0.0\nowner: owner\ntype: reference\ncode: []\n---\n# Alpha\n", encoding="utf-8")
        (self.root / "docs" / "docs.json").write_text(json.dumps({"apps": [], "topics": []}), encoding="utf-8")

    def build(self):
        I.build(self.root)

    def test_text_files_and_pages_carry_badge(self):
        self.build()
        own = B.own_info()[1]
        for rel in ("docs/features/index.md", "docs/architecture/decisions.md"):
            text = (self.root / rel).read_text(encoding="utf-8")
            self.assertRegex(text, r"<!-- Generated by luismc-docs %s \((latest|update: [\d.]+|latest: unknown)\) -->" % re.escape(own), rel)
        llms = (self.root / "docs/llms.txt").read_text(encoding="utf-8")
        self.assertRegex(llms.splitlines()[0], r"^Generated by luismc-docs %s \(" % re.escape(own))
        for rel in ("docs/index.html", "docs/_site/features/alpha/spec.html"):
            f = self.root / rel
            if not f.is_file():
                continue
            self.assertIn('class="gen-badge"', f.read_text(encoding="utf-8"), rel)
        self.assertEqual(I.stale_generated(self.root), [])

    def test_freshness_ignores_badge_line(self):
        self.build()
        f = self.root / "docs/llms.txt"
        f.write_text(re.sub(r"^Generated by luismc-docs.*$", "Generated by luismc-docs 0.0.1 (update: 9.9.9)", f.read_text(encoding="utf-8"), flags=re.M), encoding="utf-8")
        self.assertEqual(I.stale_generated(self.root), [])
        f.write_text(f.read_text(encoding="utf-8") + "extra\n", encoding="utf-8")
        self.assertEqual(I.stale_generated(self.root), ["docs/llms.txt"])

    def test_site_css_matches_default_page_colours_and_font(self):
        default = (PLUGIN / "design" / "default-design.css").read_text(encoding="utf-8")
        light_paper = re.search(r"--paper:\s*(#\w+)", default).group(1).lower()
        dark_paper = re.search(r"data-theme=\"dark\"\]\s*\{\s*--paper:\s*(#\w+)", default).group(1).lower()
        for css in (I.CSS, DS.GALLERY_CSS):
            low = css.lower()
            self.assertIn("--bg:" + light_paper, low)
            self.assertIn("--bg:" + dark_paper, low)
            self.assertIn("14.4px", css)
            self.assertNotIn("16px/", css)

    def test_gallery_has_badge(self):
        folder = Path(self.tmp.name) / "ds"
        folder.mkdir()
        (folder / "README.md").write_text("# DS\n\nVersion 1\n", encoding="utf-8")
        out = DS.build_visuals(folder)
        self.assertIn('class="gen-badge"', out.read_text(encoding="utf-8"))


class RecordPages(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.git("init", "-q", "-b", "main")
        (self.root / ".claude").mkdir()
        (self.root / ".claude" / "artifacts.json").write_text("{}\n", encoding="utf-8")
        self.git("commit", "-q", "--allow-empty", "-m", "seed")
        self.ok("init", "--project", "Demo", "--timezone", "Europe/Lisbon", "--label", "Lisbon",
                "--windows-timezone", "GMT Standard Time", "--project-prefix", "DS")
        self.ok("feature-new", "--key", "alpha", "--title", "Alpha", "--prefix", "AL", "--apps", "plugin")

    def git(self, *a):
        subprocess.run(["git", "-C", str(self.root), "-c", "user.email=t@t", "-c", "user.name=t", *a], check=True, capture_output=True, env=ENV)

    def run_cmd(self, *a):
        r = subprocess.run([sys.executable, str(SCRIPTS / "project_artifacts.py"), *a, *([] if a[0] == "check" else ["--no-push"])], cwd=str(self.root),
                           capture_output=True, text=True, encoding="utf-8", env=ENV)
        return r.returncode, r.stdout, r.stderr

    def ok(self, *a):
        code, out, err = self.run_cmd(*a)
        self.assertEqual(code, 0, out + err)
        return out, err

    def pages(self):
        d = self.root / "docs" / "artifacts"
        return [d / "full-progress-demo.html", d / "feature-alpha.html"]

    def test_badge_in_both_pages(self):
        own = B.own_info()[1]
        for p in self.pages():
            text = p.read_text(encoding="utf-8")
            self.assertRegex(text, r'class="gen-badge"[^>]*>luismc-docs %s <span class="gen-flag gen-\w+">' % re.escape(own), p.name)

    def test_base_font_is_scaled(self):
        for p in self.pages():
            text = p.read_text(encoding="utf-8")
            self.assertIn("font-size: 14.4px;", text)
            self.assertNotIn("font-size: 16px", text)
        self.assertIn("font-size: 9.9px", self.pages()[0].read_text(encoding="utf-8"))  # was 11px

    def test_project_design_changes_accent_not_page_colour(self):
        css = (PLUGIN / "design" / "default-design.css").read_text(encoding="utf-8")
        css = css.replace("--paper: #F5F6F8", "--paper: #f4f6f1").replace("--paper: #0F141B", "--paper: #0b0f0d").replace("#2D46C8", "#7a2dc8")
        f = Path(self.tmp.name) / "mine.css"
        f.write_text(css, encoding="utf-8")
        out, err = self.ok("design", "set", str(f))
        self.assertIn("ignored", err)
        for p in self.pages():
            text = p.read_text(encoding="utf-8")
            block = re.search(r'<style id="design-tokens">(.*?)</style>', text, re.S).group(1)
            self.assertIn("#7a2dc8", block)  # the accent applies
            self.assertNotIn("#f4f6f1", block)
            self.assertNotIn("#0b0f0d", block)
            self.assertIn("#F5F6F8", block)  # the default page colour stays, light and dark
            self.assertIn("#0F141B", block)
            self.assertEqual(R.check_tokens(block), [])
        code, o, e = self.run_cmd("check")
        self.assertEqual(code, 0, o + e)

    def test_latest_flag_does_not_make_pages_stale(self):
        base = Path(self.tmp.name) / "mk"
        fake_market(base, "99.0.0")
        env = dict(ENV, **{B.ENV_DIR: str(base)})
        r = subprocess.run([sys.executable, str(SCRIPTS / "project_artifacts.py"), "render", "--all", "--no-push"], cwd=str(self.root),
                           capture_output=True, text=True, env=env)
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertIn("update: 99.0.0", self.pages()[1].read_text(encoding="utf-8"))
        code, out, err = self.run_cmd("check")      # no clone here: the fresh render says unknown
        self.assertEqual(code, 0, out + err)
        code, out, err = self.run_cmd("render")
        self.assertIn("nothing to do", out)

    def test_ignored_tokens_lists_neutrals(self):
        got = R.ignored_tokens(":root{--paper:#fff;--signal:#123;--surface-2:#eee;--ink:#000}")
        self.assertEqual(got, ["--ink", "--paper", "--surface-2"])


